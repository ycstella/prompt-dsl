type CodeBuilder struct {
	promptNode    *PromptNode
	fileName      string
	b             strings.Builder
	outputTypeStr string
	model         string
	goimport      []goimport
	genPrompCode  *final
	outname       string
	output        string
}

func NewCodeBuilder(p *PromptNode, fileName string, g *final) *CodeBuilder {
	var b strings.Builder
	return &CodeBuilder{
		promptNode:   p,
		fileName:     fileName,
		b:            b,
		goimport:     p.Goimport,
		genPrompCode: g,
	}
}

// output为数组的处理
func (c *CodeBuilder) isArray() error {
	// fmt.Println("😅")
	if len(c.promptNode.ModelFields) > 0 {
		fmt.Println("root.ModelFields:", c.promptNode.ModelFields)
	}
	c.outputTypeStr = c.fileName + "OutputContext"
	if c.promptNode.outputspectNodes.IsArray {
		c.outputTypeStr = "[]" + c.fileName + "OutputContext"
	}
	if len(c.promptNode.OutFields) == 0 {
		c.outputTypeStr = "[]string"
	}
	if len(c.promptNode.ModelFields) > 0 {
		c.model = c.fileName + "ModelOutputContext"
		if c.promptNode.outputspectNodes.IsArray {
			c.model = "[]" + c.fileName + "ModelOutputContext"
		}
	}
	return nil
}

// 写包名和注释
func (c *CodeBuilder) writeGeneratedHeader() error {

	c.b.WriteString("// Code generated by PromptDSL. DO NOT EDIT.\n")
	c.b.WriteString(fmt.Sprintf("package %s\n\n", "main"))
	return nil
}

// 写入import
func (c *CodeBuilder) buildImport() error {
	//after+fix
	afterCode := strings.Join(c.promptNode.AfterCode, "\n")
	fixCode := strings.Join(c.promptNode.FixCode, "\n")
	beforeCode := strings.Join(c.promptNode.BeforeCode, "\n")

	allCode := afterCode + "\n" + fixCode + "\n" + beforeCode
	// renderImportSectionWithAlias()
	pkgs := inferImportsFromCode(allCode)
	//main

	requiredPkgs := []string{"os", "log", "fmt", "github.com/ycstella/prompt-dsl/service", "github.com/ycstella/prompt-dsl/codegen", "github.com/ycstella/prompt-dsl/config", "encoding/json", "path/filepath"}
	if len(c.promptNode.FixCode) == 0 || len(c.promptNode.AfterCode) == 0 {
		requiredPkgs = []string{"os", "log", "fmt", "github.com/ycstella/prompt-dsl/service", "strings", "github.com/ycstella/prompt-dsl/config", "encoding/json", "path/filepath"}
	}
	for _, req := range requiredPkgs {
		has := false
		for _, pkg := range pkgs {
			if pkg == req {
				has = true
				break
			}
		}
		if !has {
			pkgs = append(pkgs, req)
		}
	}
	importBlock := renderImportSectionWithAlias(c.goimport, pkgs)

	c.b.WriteString(importBlock)
	return nil
}
func (c *CodeBuilder) subStruct() {
	for _, substruct := range c.promptNode.SubFields {
		c.b.WriteString("type " + c.fileName + capitalizeFirst(substruct.Name) + " struct {\n")
		for _, field := range substruct.Fields {
			c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", field.Name, field.Type, field.JsonName))
		}
		c.b.WriteString("}\n\n")
	}
	c.b.WriteString("type " + c.fileName + " struct {\n")
	c.b.WriteString("    Input " + c.fileName + "InputContext\n")
	if len(c.promptNode.OutFields) > 0 {
		c.b.WriteString("    Output " + c.fileName + "OutputContext\n")
	}

	if len(c.promptNode.ModelFields) > 0 {
		c.b.WriteString("    ModelOutput " + c.fileName + "ModelOutputContext\n")
	}
	c.b.WriteString("}\n\n")
}
func (c *CodeBuilder) buildInputContext() {
	c.b.WriteString("type " + c.fileName + "InputContext struct {\n")
	for _, field := range c.promptNode.InFields {
		fieldName := capitalizeFirst(field.Name)
		if field.Type == "struct" {
			c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, c.fileName+fieldName, field.JsonName))
			continue
		}
		if field.Type == "[]struct" {
			c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, "[]"+c.fileName+fieldName, field.JsonName))
			continue
		}
		c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, field.Type, field.JsonName))
	}
	c.b.WriteString("}\n\n")
}
func (c *CodeBuilder) buildOutputContext() {
	if len(c.promptNode.OutFields) > 0 {
		c.b.WriteString("type " + c.fileName + "OutputContext struct {\n")
		for _, field := range c.promptNode.OutFields {
			skip := false
			for _, ann := range field.Annotations {
				if ann == "outignore" {
					skip = true
					break
				}
			}
			log.Println(field.Annotations)
			if skip {
				continue
			}
			fieldName := capitalizeFirst(field.Name)
			if field.Type == "struct" {
				c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, c.fileName+fieldName, field.JsonName))
				continue
			}
			if field.Type == "[]struct" {
				c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, "[]"+c.fileName+fieldName, field.JsonName))
				continue
			}
			c.b.WriteString(fmt.Sprintf("    %s %s `json:\"%s\"`\n", fieldName, field.Type, field.JsonName))
		}
		c.b.WriteString("}\n\n")
	}
}
